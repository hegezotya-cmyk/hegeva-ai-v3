assert(/missingRequired/.test(autoRepair) && /REAL WORKING FLOWS/.test(autoRepair), 'Auto repair must explicitly target missing capabilities')
assert(/If edit is missing/.test(autoRepair), 'Auto repair must explicitly harden missing edit/update capability')
assert(/retryGate\.accepted/.test(autoRepair), 'Auto repair must treat a fully accepted repaired candidate as capability improvement')
assert(/retryGate\.capabilityScore > firstGate\.capabilityScore/.test(autoRepair), 'Auto repair must only accept measurable capability improvement')
assert(/retryGate\.missingRequired\.length < firstGate\.missingRequired\.length/.test(autoRepair), 'Auto repair must accept candidates with fewer missing required capabilities')
assert(/specImproved/.test(autoRepair) && /retryMatch\.score >= firstMatch\.score \+ 10/.test(autoRepair), 'Auto repair must accept meaningful spec-match improvement')
assert(/retryIsSafe/.test(autoRepair), 'Spec repair must be guarded against major capability regression')
assert(/localStorage\.removeItem\(REPAIR_KEY\)/.test(autoRepair), 'Auto repair must unlock retry state after a non-improving attempt')
assert(/looksLikeHtmlDocument\(retryHtml\)/.test(autoRepair), 'Auto repair retry HTML must be verified before selection')
assert(/localStorage\.setItem\(HTML_KEY, retryHtml\)/.test(autoRepair), 'Accepted repaired candidate must replace the saved build')

