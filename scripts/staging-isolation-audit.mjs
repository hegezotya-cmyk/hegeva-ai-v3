import assert from "node:assert/strict"
import { readFileSync } from "node:fs"

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8")
const api = read("wrangler.staging.jsonc")
const ui = read("v0-app/wrangler.staging.jsonc")
const workflow = read(".github/workflows/staging-deploy.yml")
const auth = read("src/auth.js")
const analytics = read("v0-app/components/analytics-consent.tsx")

assert.match(api, /"name": "hegeva-ai-v3-staging"/)
assert.match(api, /"PAYMENT_MODE": "test"/)
assert.doesNotMatch(api, /"PAYMENT_MODE": "live"/)
assert.match(api, /"database_name": "hegeva-ai-staging-db"/)
assert.doesNotMatch(api, /hegeva-ai-db/gi)
assert.match(api, /"STAGING_SECRETS_CONFIGURED": "(?:pending|confirmed)"/)
assert.match(ui, /"name": "hegeva-ai-v3-v0-staging"/)
assert.match(ui, /"service": "hegeva-ai-v3-staging"/)
assert.doesNotMatch(ui, /"service": "hegeva-ai-v3"/)
assert.match(workflow, /workflow_dispatch:/)
assert.doesNotMatch(workflow, /\n\s*push:/)
assert.doesNotMatch(workflow, /actions\/(?:checkout|setup-node)@v4/, "staging workflow must avoid the deprecated Node 20 action runtime")
assert.match(workflow, /actions\/checkout@v5/)
assert.match(workflow, /actions\/setup-node@v5/)
assert.match(workflow, /CLOUDFLARE_STAGING_API_TOKEN/)
assert.match(workflow, /environment: staging/)
assert.match(workflow, /NEXT_PUBLIC_APP_ENV: staging/, "staging UI builds must disable production analytics defaults")
assert.match(workflow, /NEXT_PUBLIC_GA_MEASUREMENT_ID: \$\{\{ vars\.STAGING_GA_MEASUREMENT_ID \}\}/, "staging analytics must use only the staging environment variable")
assert.match(workflow, /preflight:\s*[\s\S]*needs: verify[\s\S]*npm run staging:preflight/, "the check operation must validate staging configuration and secret presence")
assert.match(workflow, /deploy:\s*[\s\S]*needs: \[verify, preflight\]/, "deployment must wait for verification and preflight")
assert.match(workflow, /npm run staging:db:migrate\s*[\s\S]*npm run staging:api:deploy/, "staging schema migrations must complete before API deployment")
assert.match(auth, /EMAIL_FROM/)
assert.match(auth, /trustedOrigins/)
assert.match(analytics, /NEXT_PUBLIC_APP_ENV/)
assert.match(analytics, /NEXT_PUBLIC_GA_MEASUREMENT_ID/)
assert.match(analytics, /IS_STAGING \? "" : "G-TK99HP2BG7"/)
console.log("Staging isolation audit passed")
